'use strict';
const assert=require('node:assert/strict');
const {Probe,PROBE_KIND,bytes}=require('../transfer.js');
const alice=new Probe('client_alice');
const bob=new Probe('client_bob');
const carol=new Probe('client_carol');
const req=alice.start('probe_001');
assert.equal(req.payload.kind,PROBE_KIND);
assert(bytes(req)<128000);
assert.equal(alice.responses,0);
assert.equal(alice.accept(req.payload).kind,'self');
assert.equal(alice.responses,0);
assert.equal(bob.accept(req.payload).kind,'request');
assert.equal(bob.hasRequest,true);
assert.equal(carol.accept(req.payload).kind,'request');
const ack=bob.response();
assert.equal(bob.hasRequest,false);
assert.equal(ack.payload.action,'ack');
assert.equal(bob.accept(ack.payload).kind,'self');
assert.equal(alice.accept(ack.payload).kind,'ack');
assert.equal(alice.responses,1);
assert.equal(alice.accept(ack.payload).duplicate,true);
assert.equal(alice.responses,1);
const cack=carol.response();
assert.equal(alice.accept(cack.payload).count,2);
const unrelated={...cack.payload,requestId:'some_other_probe'};
assert.equal(alice.accept(unrelated).kind,'unrelated');
assert.equal(alice.responses,2);
const newRequest=alice.start('probe_002');
assert.equal(alice.responses,0);
assert.equal(alice.accept(cack.payload).kind,'unrelated');
const invalid={...newRequest.payload,clientId:'<script>'};
assert.equal(bob.accept(invalid).kind,'invalid');
assert.equal(bob.response(),null);
assert.equal(alice.responses,0);
assert.throws(()=>new Probe('in valid'),/ID/);
assert.throws(()=>alice.start('???'),/ID/);
console.log('vctrmemo v0.10 probe: self echoes ignored, manual remote ACK, duplicates, multiple peers, replay isolation PASS');
